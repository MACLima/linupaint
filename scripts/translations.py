# Kept identical in every language: shortcuts and pure placeholders.
SAME = {"%1 x %2", "%1, %2", "%1x", " %", "LinuPaint", "GIF (*.gif)", "PNG (*.png)",
        "JPEG (*.jpg *.jpeg *.jpe *.jfif)"}


def fill(path: Path, column: int) -> list[str]:
    tree = ET.parse(path)
    missing = []
    for msg in tree.getroot().iter("message"):
        src = msg.findtext("source")
        tr = msg.find("translation")
        if src in T:
            tr.text = T[src][column]
            tr.attrib.pop("type", None)
        elif src in SAME:
            tr.text = src
            tr.attrib.pop("type", None)
        elif not (src.startswith("Ctrl") or src in {"Del", "Esc"}):
            missing.append(src)
    tree.write(path, encoding="utf-8", xml_declaration=True)
    return missing


